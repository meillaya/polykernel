// Per-op kernel emitters. Each writes a complete, self-contained .cu (kernel +
// host launch_* entry) to `os`. Todo 9 adds emitGeluCuda / emitSiluCuda; Todo 10
// adds emitMatMulCuda / emitSoftmaxCuda here and registers them in the dispatch.
