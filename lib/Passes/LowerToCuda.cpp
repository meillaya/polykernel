// PolyKernel out-of-tree MLIR dialect: the `--lower-to-cuda` source-emitter pass
// (Todo 8 / Wave 2).
//
//===----------------------------------------------------------------------===//
//
// EMISSION APPROACH (Pinned contract F). This pass is a CUSTOM SOURCE EMITTER,
// not an IR-to-IR lowering: it walks the PolyKernel IR, recognizes the compute
// op kinds present, and for each one STRING-EMITS a portable CUDA/HIP kernel
// source file (.cu) into --output-dir (default kernels/generated). It does NOT
// use the upstream gpu-to-llvm / convert-to-llvm pipelines. The emitted .cu is
// written against kernels/template/kernel_common.h, so the SAME file compiles
// unchanged under `nvcc -DPOLYKERNEL_CUDA` (Wave 2) and `hipcc -DPOLYKERNEL_HIP`
// (Wave 4); the nvcc driver (tools/polykernel-bench/nvcc_driver.py) then compiles
// it to PTX + ptxas stats.
//
// Todo 8 emits a PRE-WRITTEN, TEMPLATED kernel per recognized op kind: the
// RMSNorm kernel below is emitted verbatim (epsilon and weight-presence are
// runtime kernel parameters, so one emitted .cu handles any shape/epsilon). The
// deliverable is the emission PIPELINE — walk IR -> dispatch by op kind ->
// string-emit .cu text -> write file. Todo 9/10 grow the dispatch table with
// gelu/silu/matmul/softmax emitters and add real per-op shape/attr
// parameterization of the emitted text.
//
//===----------------------------------------------------------------------===//

